    // SERVER-025: Service Recovery Handling
    @Test
    @DisplayName("SERVER-025: Service Recovery Handling")
    public void testServer025_ServiceRecoveryHandling() {
        MockDataSource ds = new MockDataSource();
        ds.setSimulateFailure(true);
        HealthController controller = new HealthController(ds);

        // Initially DOWN
        ResponseEntity<Map<String, Object>> downResponse = controller.getHealth();
        assertEquals(HttpStatus.SERVICE_UNAVAILABLE, downResponse.getStatusCode());

        // Recovered UP
        ds.setSimulateFailure(false);
        ResponseEntity<Map<String, Object>> upResponse = controller.getHealth();
        assertEquals(HttpStatus.OK, upResponse.getStatusCode());
        assertEquals("UP", upResponse.getBody().get("status"));
    }

